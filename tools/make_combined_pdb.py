"""Build a PyMOL session loader for a submission's 20 complexes, as NAMED objects.

    python3 tools/make_combined_pdb.py submissions/12_icm_redock_af3
    python3 tools/make_combined_pdb.py --all

Writes <submission>/visualize/load_all.pml. Open it with:

    pymol submissions/12_icm_redock_af3/visualize/load_all.pml

Each complex becomes its own object named after the ligand (OCNT-2312554, ...), so the
PyMOL object panel reads as ligand names rather than state numbers.

WHY NOT ONE MULTI-MODEL FILE. The first version of this tool concatenated the 20 PDBs
with MODEL/ENDMDL records. That is wrong here for two reasons, both of which showed up as
"mangled ligands" and distorted secondary structure:

  1. PyMOL states must share an identical atom composition. These complexes have
     DIFFERENT ligands with different atom counts, so PyMOL builds the object from state 1
     and misassigns every later state's coordinates onto those atoms - corrupting the
     ligand and the backbone alike.
  2. It dropped the CONECT records (the shipped PDBs do carry them), leaving PyMOL to
     guess ligand bonds by distance.

Separate objects avoid both: each file is parsed on its own, with its own CONECT records.

WHY NATIVE PyMOL COMMANDS. A .pml file is PyMOL's own command language, NOT Python. An
earlier version emitted `cmd.load(...)` and `def ...():` lines, which PyMOL silently
ignored - the script appeared to do nothing. Python has to live inside a
`python` / `python end` block. Paths are written absolute, because PyMOL resolves
relative paths against the current working directory, not the script's location.
"""
import argparse, os, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PML_HEADER = """# Generated by tools/make_combined_pdb.py - do not edit, regenerate instead.
# {label}: {n} complexes, each loaded as its own named object.
#
# Commands added below:
#   align_all   superpose every complex onto the first (by protein chain A)
#   lig_only    hide protein, show just the ligands and haem
#   show_all    undo lig_only
#   grid        tile the complexes side by side

"""

PML_FOOTER = """
hide everything
show cartoon, polymer
show sticks, resn LIG
show sticks, resn HEM
show spheres, elem Fe
set sphere_scale, 0.3, elem Fe
util.cbaw resn LIG
color firebrick, resn HEM
color grey80, polymer
dss
orient resn LIG

python
from pymol import cmd
_names = {names!r}

def align_all():
    ref = _names[0]
    for n in _names[1:]:
        cmd.align("polymer and " + n, "polymer and " + ref)
    cmd.orient("resn LIG")

def lig_only():
    cmd.hide("cartoon")
    cmd.show("sticks", "resn LIG or resn HEM")

def show_all():
    cmd.show("cartoon", "polymer")

def grid():
    cmd.set("grid_mode", 1)

for _f in (align_all, lig_only, show_all, grid):
    cmd.extend(_f.__name__, _f)

print("")
print("Loaded %d complexes as named objects." % len(_names))
print("Commands: align_all, lig_only, show_all, grid")
python end
"""


def build(subdir):
    src = os.path.join(subdir, "submission")
    if not os.path.isdir(src):
        return None
    pdbs = sorted(f for f in os.listdir(src) if f.endswith(".pdb"))
    if not pdbs:
        return None
    out = os.path.join(subdir, "visualize")
    os.makedirs(out, exist_ok=True)
    names = [f[:-4] for f in pdbs]
    # absolute paths: PyMOL resolves relative paths against the cwd, not the script
    body = "".join(f'load {os.path.abspath(os.path.join(src, f))}, {f[:-4]}\n'
                   for f in pdbs)
    path = os.path.join(out, "load_all.pml")
    with open(path, "w") as g:
        g.write(PML_HEADER.format(label=os.path.basename(subdir), n=len(pdbs)))
        g.write(body)
        g.write(PML_FOOTER.format(names=names))
    return path, len(pdbs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("subdir", nargs="?")
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    if a.all:
        base = os.path.join(HERE, "submissions")
        targets = [os.path.join(base, d) for d in sorted(os.listdir(base))
                   if os.path.isdir(os.path.join(base, d, "submission"))]
    elif a.subdir:
        targets = [a.subdir]
    else:
        ap.error("give a submission directory or --all")
    for t in targets:
        r = build(t)
        print(f"{os.path.basename(t):28} " +
              (f"{r[1]:2d} objects -> {r[0]}" if r else "no submission/*.pdb, skipped"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
