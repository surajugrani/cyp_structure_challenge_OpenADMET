"""
Submission 01, step 1: write one Boltz-2 input YAML per blinded ligand.

Baseline settings, but chemically complete: full-length CYP3A4 (UniProt P08684, 503 aa),
the haem cofactor, and the ligand. No templates, no pocket restraints, MSA generated by
Boltz's own server (`--use_msa_server`), so the run depends on no local MSA files.

The organizers' own tutorial YAML omits the haem. That is not followed here: CYP3A4
without its haem leaves the cofactor cavity empty and invites the ligand into it, and the
cryo-EM ground truth contains the haem. The haem is supplied as CCD component HEM, the
same three-letter code used throughout analyses 01-05.

Usage:
    python3 scripts/01_make_yamls.py

Outputs:
    inputs/<Molecule_Name>.yaml   one per ligand (20)
"""

import csv
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(HERE))
INPUTS = os.path.join(HERE, "inputs")

# Chain B is the haem (CCD HEM), chain C the blinded ligand.
TEMPLATE = """version: 1
sequences:
  - protein:
      id: [A]
      sequence: {seq}
  - ligand:
      id: [B]
      ccd: HEM
  - ligand:
      id: [C]
      smiles: '{smiles}'
"""


def read_fasta(path):
    with open(path) as f:
        return "".join(l.strip() for l in f if not l.startswith(">"))


def main():
    os.makedirs(INPUTS, exist_ok=True)
    seq = read_fasta(os.path.join(ROOT, "input", "CYP3A4_protein_sequence.fasta"))
    print(f"CYP3A4 sequence: {len(seq)} aa")

    csv_path = os.path.join(ROOT, "input", "cyp-challenge-TEST-BLINDED_structures.csv")
    n = 0
    with open(csv_path) as f:
        for row in csv.DictReader(f):
            name, smi = row["Molecule_Name"].strip(), row["SMILES"].strip()
            if not name or not smi:
                continue
            # single quotes wrap the SMILES in the YAML, so a literal ' would break it
            assert "'" not in smi, f"SMILES for {name} contains a quote"
            with open(os.path.join(INPUTS, f"{name}.yaml"), "w") as out:
                out.write(TEMPLATE.format(seq=seq, smiles=smi))
            n += 1
    print(f"wrote {n} YAMLs to {INPUTS}")
    assert n == 20, f"expected 20 ligands, got {n}"


if __name__ == "__main__":
    main()
